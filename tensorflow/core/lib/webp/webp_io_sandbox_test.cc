namespace {
std::string ReadFile(const std::string& path) {
  std::ifstream t(path, std::ios::binary);
  std::stringstream buffer;
  buffer << t.rdbuf();
  return buffer.str();
}
}  // namespace

TEST(WebPIOSandboxTest, DecodeWebPAnimation) {
  std::string file_path =
      "third_party/tensorflow/core/lib/webp/testdata/bouncy_ball.webp";
  std::string webp_string = ReadFile(file_path);
  ASSERT_FALSE(webp_string.empty())
      << "Failed to read test data from " << file_path;

  int width, height, channels;
  bool has_animation;
  ASSERT_TRUE(tensorflow::webp::DecodeWebPHeader(webp_string, &width, &height,
                                                 &channels, &has_animation));
  ASSERT_TRUE(has_animation);

  std::vector<std::unique_ptr<uint8_t[]>> allocated_buffers;
  auto allocate_output = [&allocated_buffers](int num_frames, int width,
                                              int height,
                                              int channels) -> uint8_t* {
    size_t size = num_frames * width * height * channels;
    auto buf = std::make_unique<uint8_t[]>(size);
    uint8_t* ptr = buf.get();
    allocated_buffers.push_back(std::move(buf));
    return ptr;
  };

  std::string error_string;
  uint8_t* output = tensorflow::webp::DecodeWebPAnimation(
      webp_string, allocate_output, &error_string, /*expand_animations=*/true,
      /*use_threads=*/false);

  EXPECT_NE(output, nullptr);
  EXPECT_TRUE(error_string.empty()) << "Error: " << error_string;

  ASSERT_FALSE(allocated_buffers.empty());
  EXPECT_EQ(output, allocated_buffers.back().get());

  // Check that the buffer is not completely empty (all zeros).
  size_t size = width * height * channels;
  bool all_zeros = true;
  for (size_t i = 0; i < size; ++i) {
    if (output[i] != 0) {
      all_zeros = false;
      break;
    }
  }
  EXPECT_FALSE(all_zeros) << "Output buffer is all zeros";
}
